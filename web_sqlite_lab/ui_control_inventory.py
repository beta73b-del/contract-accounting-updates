"""Inventory interactive controls in original Web HTML; no user data is read.

This is a coverage catalogue, NOT a passed functional test matrix.
"""
from __future__ import annotations
from html.parser import HTMLParser
from pathlib import Path
import csv
import json
import re
import sys

class Inventory(HTMLParser):
    def __init__(self):
        super().__init__()
        self.controls=[]
        self.open=[]
    def handle_starttag(self,tag,attrs):
        a=dict(attrs)
        clickable=tag in ("button","input","select","textarea","a") or "onclick" in a or a.get("role")=="button"
        if clickable:
            item={"tag":tag,"id":a.get("id",""),"type":a.get("type",""),"name":a.get("name",""),
                  "class":a.get("class",""),"target":a.get("href",""),
                  "disabled_by_default":"disabled" in a,
                  "data_action":a.get("data-action",""),
                  "test_status":"NOT_RUN","comment":"Dynamic buttons generated by JS require additional runtime inventory"}
            self.controls.append(item)

def inventory(original_web_dir,target):
    source=Path(original_web_dir)/"app"
    if not (source/"index.html").is_file():
        raise FileNotFoundError(source/"index.html")
    target=Path(target)
    target.parent.mkdir(parents=True,exist_ok=True)
    files=list(source.glob("*.html"))
    records=[]
    for f in sorted(files):
        parser=Inventory()
        parser.feed(f.read_text(encoding="utf-8-sig"))
        for number,row in enumerate(parser.controls,1):
            row["file"]=f.name
            row["sequence"]=number
            row["check_id"]=f"{f.stem}:{row['id'] or row['name'] or row['tag']+'-'+str(number)}"
            records.append(row)
    if not records:raise ValueError("No controls found")
    cols=["check_id","file","sequence","tag","id","name","type","class","target",
          "data_action","disabled_by_default","test_status","comment"]
    with target.open("w",encoding="utf-8-sig",newline="") as fp:
        writer=csv.DictWriter(fp,fieldnames=cols);writer.writeheader();writer.writerows(records)
    return {"files":len(files),"htmlControls":len(records),"buttons":sum(r["tag"]=="button" for r in records),
            "inputs":sum(r["tag"]=="input" for r in records),
            "dynamicJsControls":"NOT_INVENTORIED_YET","tested":0,"coverage":"NOT_VERIFIED"}

if __name__=="__main__":
    if len(sys.argv)!=3:raise SystemExit("Usage: python ui_control_inventory.py <existing-web-root> <private-output.csv>")
    print(json.dumps(inventory(sys.argv[1],sys.argv[2]),ensure_ascii=False))
